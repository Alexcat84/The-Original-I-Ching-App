function leggeName(n) {
  return LEGGE_NAMES[n] ?? String(wilhelm[String(n)]?.english ?? "").trim();
}

async function main() {
  const symbolismHtml = await loadLeggeSymbolismHtml({ live });
  const images = parseLeggeSymbolismAppendix(symbolismHtml);

  const dataset = {};
  const issues = [];

  for (let n = 1; n <= 64; n++) {
    const html = await loadLeggeTextHtml(n, { live });
    const parsed = parseLeggeTextPage(html);
    const judgment = String(parsed.judgment ?? "").trim();
    const image = String(images[n] ?? "").trim();

    if (!judgment) issues.push({ n, why: "empty judgment" });
    if (!image) issues.push({ n, why: "empty Great Symbolism" });

    const lines = {};
    for (let pos = 1; pos <= 6; pos++) {
      lines[String(pos)] = { text: String(parsed.lineByPos[pos] ?? "").trim() };
      if (!lines[String(pos)].text) issues.push({ n, pos, why: "empty line" });
    }

    dataset[String(n)] = {
      hex: n,
      hex_font: String(wilhelm[String(n)]?.hex_font ?? "").trim(),
      name: leggeName(n),
      legge_judgment: { text: judgment },
      legge_image: { text: image },
      legge_lines: lines,
      ...(parsed.supernumerary ? { yong_supernumerary: parsed.supernumerary.trim() } : {}),
    };

    console.log(
      `  Hex ${String(n).padStart(2, "0")}: ${dataset[String(n)].name} J=${judgment.length}ch I=${image.length}ch`,
    );
  }

  const body =
    "// Generated by tools/ingest-legge-sacred.mjs from sacred-texts.com.\n" +
    "// Source: https://www.sacred-texts.com/ich/index.htm (James Legge, 1882/1899).\n" +
    "// Translator: James Legge. Public domain.\n\n" +
    "export default " +
    JSON.stringify(dataset, null, 2) +
    ";\n";
  await writeFile(finalOut, body, "utf8");
  console.log("\nWrote", finalOut);

  if (issues.length > 0) {
    console.warn(`\nFinished with ${issues.length} unresolved empty fields:`);
    for (const it of issues.slice(0, 20)) console.warn("  ", it);
    if (issues.length > 20) console.warn(`  … and ${issues.length - 20} more`);
    process.exitCode = 1;
  } else {
    console.log("\nAll 64 hexagrams ingested cleanly from sacred-texts.");
  }
}

await main();
