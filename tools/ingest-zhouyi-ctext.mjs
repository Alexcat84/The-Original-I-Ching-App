/**
 * Ingest Zhou Yi (周易) from Chinese Text Project (ctext.org).
 *
 * Primary source: ctext gettext API + chapter HTML for 大象傳 (Great Symbolism).
 * Replaces freizl/yijing as the canonical intermediate for build-hexagrams.mjs.
 *
 * Pipeline:
 *  1. For each hex 1..64 fetch cached ctext JSON + HTML (tools/output/fidelity-gold/).
 *  2. Parse with scripts/lib/hexagram-fidelity-ctext.mjs (same gold as verify harness).
 *  3. Normalize to traditional canonical form (NFKC + variant map).
 *  4. Write scripts/iching_zhouyi_translation.mjs.
 *
 * Run: npm run ingest:zhouyi
 * Flags: --live (refetch from ctext.org)
 */

import { writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import {
  mergeCtextGold,
  parseCtextZhouYi,
  parseCtextZhouYiFromHtml,
} from "../scripts/lib/hexagram-fidelity-ctext.mjs";
import { loadCtextHtml, loadCtextJson } from "../scripts/lib/hexagram-fidelity-fetch.mjs";
import { toCanonicalZhouYiText } from "../scripts/lib/hexagram-fidelity-normalize.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const finalOut = join(root, "scripts", "iching_zhouyi_translation.mjs");

const live = process.argv.includes("--live");

const wilhelmModule = await import(
  pathToFileURL(join(root, "scripts", "iching_wilhelm_translation.mjs")).href
);
const wilhelm = wilhelmModule.default;

function canon(text) {
  return toCanonicalZhouYiText(text);
}

async function main() {
  const dataset = {};
  const issues = [];

  for (let n = 1; n <= 64; n++) {
    const apiPayload = await loadCtextJson(n, { live });
    const html = await loadCtextHtml(n, { live });
    const gold = mergeCtextGold(parseCtextZhouYi(apiPayload), parseCtextZhouYiFromHtml(html));

    const lines = {};
    for (let pos = 1; pos <= 6; pos++) {
      const raw = gold.lines[pos] ?? "";
      lines[String(pos)] = { text: canon(raw) };
      if (!lines[String(pos)].text) {
        issues.push({ n, pos, why: "empty line" });
      }
    }

    const judgment = canon(gold.judgment);
    const image = canon(gold.image ?? "");
    const w = wilhelm[String(n)];

    if (!judgment) issues.push({ n, why: "empty judgment" });
    if (!image) issues.push({ n, why: "empty image (大象)" });

    dataset[String(n)] = {
      hex: n,
      hex_font: String(w?.hex_font ?? "").trim(),
      name: String(w?.trad_chinese ?? "").trim(),
      zhouyi_judgment: { text: judgment },
      zhouyi_image: { text: image },
      zhouyi_lines: lines,
      ...(gold.yongJiu ? { yong_jiu: canon(gold.yongJiu) } : {}),
      ...(gold.yongLiu ? { yong_liu: canon(gold.yongLiu) } : {}),
    };

    console.log(
      `  Hex ${String(n).padStart(2, "0")}: ${dataset[String(n)].name} J=${judgment.length}ch I=${image.length}ch`,
    );
  }

  const body =
    "// Generated by tools/ingest-zhouyi-ctext.mjs from ctext.org (gettext API + chapter HTML).\n" +
    "// Source: https://ctext.org/book-of-changes\n" +
    "// Translator: Original Zhou Yi (周易) — Classical Chinese, public domain.\n" +
    "// Position labels stripped; traditional canonical normalization applied at ingest.\n\n" +
    "export default " +
    JSON.stringify(dataset, null, 2) +
    ";\n";
  await writeFile(finalOut, body, "utf8");
  console.log("\nWrote", finalOut);

  if (issues.length > 0) {
    console.warn(`\nFinished with ${issues.length} issues:`);
    for (const it of issues) console.warn("  ", it);
    process.exitCode = 1;
  } else {
    console.log("\nAll 64 hexagrams ingested cleanly from ctext.");
  }
}

await main();
